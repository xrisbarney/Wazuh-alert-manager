const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'opensearch_dashboards.json'), 'utf8'));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
let revision = 'unknown';
const explicitRevision = process.env.WAM_SOURCE_COMMIT || process.env.GITHUB_SHA;
if (explicitRevision) {
  revision = explicitRevision.slice(0, 12);
} else {
  try {
    const gitRoot = execFileSync('git', ['rev-parse', '--show-toplevel'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    // A plugin copied below a wazuh-dashboard checkout inherits the parent's
    // .git directory. Never label that unrelated dashboard revision as the
    // plugin source revision.
    if (path.resolve(gitRoot) === root) {
      revision = execFileSync('git', ['rev-parse', '--short=12', 'HEAD'], {
        cwd: root,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      }).trim();
    }
  } catch (e) {
    // Source archives may not contain .git; the timestamp still identifies the build.
  }
}

// The Wazuh release this build targets, recorded by scripts/set-target-version.js.
// Fall back to the matrix so an un-retargeted checkout still compiles with a
// truthful value for its checked-in OSD target.
function targetWazuhVersion() {
  const recorded = pkg.wazuhAlertManager && pkg.wazuhAlertManager.targetWazuhVersion;
  if (recorded) return String(recorded);
  const matrix = JSON.parse(fs.readFileSync(path.join(root, 'supported-wazuh-versions.json'), 'utf8'));
  const matches = matrix
    .filter((entry) => entry.osdVersion === manifest.opensearchDashboardsVersion)
    .sort((a, b) => {
      if (Boolean(a.prerelease) !== Boolean(b.prerelease)) return a.prerelease ? 1 : -1;
      return b.wazuhVersion.localeCompare(a.wazuhVersion, undefined, { numeric: true });
    });
  if (!matches.length) {
    throw new Error(
      `No Wazuh release ships OSD ${manifest.opensearchDashboardsVersion}; run scripts/set-target-version.js --wazuh-version first.`
    );
  }
  return matches[0].wazuhVersion;
}

const wazuhVersion = targetWazuhVersion();
const wazuhMajor = Number(wazuhVersion.split('.')[0]);
if (!Number.isInteger(wazuhMajor) || wazuhMajor < 4) {
  throw new Error(`Unsupported target Wazuh version '${wazuhVersion}'.`);
}

const builtAt = new Date().toISOString();
const buildId = `${manifest.version}-${builtAt.replace(/[-:.TZ]/g, '')}-${revision}`;
const output = `// Generated by scripts/generate-build-info.js before yarn build.\n` +
  `export const PLUGIN_VERSION = ${JSON.stringify(manifest.version)};\n` +
  `export const TARGET_OSD_VERSION = ${JSON.stringify(manifest.opensearchDashboardsVersion)};\n` +
  `export const TARGET_WAZUH_VERSION = ${JSON.stringify(wazuhVersion)};\n` +
  `export const TARGET_WAZUH_MAJOR = ${wazuhMajor};\n` +
  `export const PLUGIN_BUILD_ID = ${JSON.stringify(buildId)};\n` +
  `export const PLUGIN_BUILT_AT = ${JSON.stringify(builtAt)};\n`;

fs.writeFileSync(path.join(root, 'common', 'build_info.ts'), output, 'utf8');
console.log(`Generated build ID ${buildId} (OSD ${manifest.opensearchDashboardsVersion}, Wazuh ${wazuhVersion})`);
