import React, { useState, useEffect } from 'react';
import {
  EuiButton,
  EuiText,
  EuiSpacer,
  EuiPanel,
  EuiLoadingSpinner,
  EuiCallOut,
  EuiFlexGroup,
  EuiFlexItem,
  EuiTitle,
} from '@elastic/eui';
import { AiAnalysis } from '../../common';
import { AlertsApiService } from '../services/api';
import { formatAbsolute } from '../design';

interface Props {
  analysis?: AiAnalysis;
  apiService: AlertsApiService;
  onGenerate: () => Promise<AiAnalysis>;
  onGenerated: (analysis: AiAnalysis) => void;
  onError: (message: string) => void;
  onToast?: (title: string, color: 'success' | 'danger' | 'primary', text?: string) => void;
  emptyMessage?: string;
}

/**
 * Generic AI-analysis panel: fetch/generate/display, with no knowledge of
 * whether it's summarizing an alert or a case - that's decided by the
 * caller's onGenerate function. See AlertFlyout / CaseFlyout for the two
 * concrete wirings. One bordered panel with a title row (title left, the
 * generate action right) on the shared flyout spacing scale (step 8.2).
 */
export const AiAnalysisTab: React.FC<Props> = ({
  analysis,
  apiService,
  onGenerate,
  onGenerated,
  onError,
  onToast,
  emptyMessage = 'No AI analysis generated yet.',
}) => {
  const [aiEnabled, setAiEnabled] = useState<boolean | null>(null);
  const [generating, setGenerating] = useState(false);

  useEffect(() => {
    apiService
      .fetchAiSettings()
      .then((res: any) => setAiEnabled(Boolean(res?.enabled && res?.configured)))
      .catch(() => setAiEnabled(false));
  }, []);

  const generate = async () => {
    try {
      setGenerating(true);
      const result = await onGenerate();
      onGenerated(result);
      onToast?.('AI analysis generated', 'success');
    } catch (e: any) {
      onError(e?.body?.message || 'Failed to generate AI analysis');
    } finally {
      setGenerating(false);
    }
  };

  if (aiEnabled === null) {
    return <EuiLoadingSpinner size="m" />;
  }

  return (
    <div className="wamAiAnalysis" data-test-subj="wamAiAnalysis">
      {!aiEnabled && (
        <>
          <EuiCallOut title="AI analysis is not configured" color="warning" iconType="alert" size="s">
            Set up an AI provider and API key under Settings &gt; AI analysis to enable this feature.
          </EuiCallOut>
          <EuiSpacer size="s" />
        </>
      )}

      <EuiPanel hasBorder paddingSize="m" className="wamAiAnalysisPanel" data-test-subj="wamAiAnalysisPanel">
        <EuiFlexGroup gutterSize="s" alignItems="center" responsive={false} className="wamPanelHeader">
          <EuiFlexItem>
            <EuiTitle size="xs">
              <h3>AI analysis</h3>
            </EuiTitle>
          </EuiFlexItem>
          <EuiFlexItem grow={false}>
            <EuiButton
              size="s"
              iconType="inspect"
              onClick={generate}
              isLoading={generating}
              isDisabled={!aiEnabled}
              data-test-subj="wamAiAnalysisGenerate"
            >
              {analysis ? 'Regenerate analysis' : 'Generate AI analysis'}
            </EuiButton>
          </EuiFlexItem>
        </EuiFlexGroup>
        <EuiSpacer size="s" />
        {analysis ? (
          <>
            <EuiText size="xs" color="subdued" data-test-subj="wamAiAnalysisProvenance">
              Generated by {analysis.provider}
              {analysis.model ? ` (${analysis.model})` : ''} at {formatAbsolute(analysis.generated_at)}
            </EuiText>
            <EuiSpacer size="s" />
            <EuiText size="s" className="wamAiAnalysisText" data-test-subj="wamAiAnalysisText">
              {analysis.text}
            </EuiText>
          </>
        ) : (
          <EuiText size="s" color="subdued" data-test-subj="wamAiAnalysisEmpty">
            {emptyMessage}
          </EuiText>
        )}
      </EuiPanel>
    </div>
  );
};
